/**
 * Prisma does not accept env() for a datasource provider, so the effective
 * schema is generated from prisma/schema.prisma: SQLite locally, PostgreSQL
 * when DATABASE_URL points at a Postgres instance (e.g. Neon on Vercel).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "prisma", "schema.prisma");
const target = join(root, "prisma", "schema.generated.prisma");

const url = process.env.DATABASE_URL ?? "";
const provider = /^postgres(ql)?:\/\//.test(url) ? "postgresql" : "sqlite";

const schema = readFileSync(source, "utf8").replace(
  /provider = "sqlite"/,
  `provider = "${provider}"`,
);

writeFileSync(
  target,
  `// GENERATED by scripts/sync-prisma-schema.mjs — edit prisma/schema.prisma instead.\n${schema}`,
);
console.log(`prisma schema generated for provider "${provider}"`);
